import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage(); const errors = []; const requests = [];
page.on('pageerror', e => errors.push(e.message));
page.on('request', r => { if (r.url().includes('securetoken')) requests.push(r.url().split('?')[0]); });
await page.goto('http://127.0.0.1:5174/product/bye-bye-makeup');
await page.getByRole('button', { name: 'Buy now', exact: true }).click();
await page.getByLabel('Full name', { exact: true }).fill('QA BASELINE LOCAL ONLY');
await page.getByLabel('Email address', { exact: true }).first().fill('baseline@glam.test');
await page.getByLabel('Mobile number').fill('03001234567');
await page.getByLabel('Street address').fill('QA Street');
await page.getByLabel('Area / neighbourhood').fill('QA Area');
await page.getByLabel('City', { exact: true }).fill('Lahore');
await page.getByLabel('Province / territory').selectOption('Punjab');
await page.getByRole('button', { name: 'Complete order' }).click();
await page.waitForURL(/order-success/);
const guest = { url: page.url(), localOrderCount: await page.evaluate(() => JSON.parse(localStorage.getItem('glam.previews.v1') || '[]').length) };
await page.reload(); await page.waitForTimeout(700);
const afterRefresh = await page.locator('main').innerText();
await mkdir('.audit', { recursive: true });
await writeFile('.audit/baseline.json', JSON.stringify({ guest, afterRefresh, errors, tokenRefreshRequests: requests.length }, null, 2));
console.log(JSON.stringify({ guest, afterRefresh: afterRefresh.slice(0, 200), errors }));
await browser.close();
